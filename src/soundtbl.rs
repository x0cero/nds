/// GetSineTable (SWI 0x1A): 64 entries, signed 16-bit, one quarter period.
pub static SINE: LazyLock<[i16; 64]> = LazyLock::new(|| {
    std::array::from_fn(|i| (32767.0 * (i as f64 * std::f64::consts::PI / 128.0).sin()).round() as i16)
});

/// GetPitchTable (SWI 0x1B): 768 entries, unsigned 16-bit, one octave split
/// into 768 steps (12 semitones x 64).
pub static PITCH: LazyLock<[u16; 768]> = LazyLock::new(|| {
    std::array::from_fn(|i| (65536.0 * ((i as f64 / 768.0).exp2() - 1.0)).round() as u16)
});

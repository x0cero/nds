//! ARM7 BIOS sound tables, exposed by SWI 0x1A/0x1B/0x1C.
//!
//! The NitroSDK sound driver calls GetPitchTable and GetVolumeTable for every
//! note it starts (Pokemon Platinum: about 880 calls per second), so an
//! emulator without them hands the driver its own index back and every note
//! comes out at the wrong pitch and volume. There is no BIOS image here, so
//! the tables have to come from somewhere else.
//!
//! Sine and pitch are exact closed forms, checked entry for entry against a
//! real BIOS dump: sine[i] = round(0x7FFF * sin(i*pi/128)) and pitch[i] =
//! round(0x10000 * (2^(i/768) - 1)), zero mismatches across all 64 and 768
//! entries. Volume is not a single curve - it is four segments, one per
//! SOUNDxCNT volume divider, each ramping the multiplier from 64 back up to
//! 127 while the divider takes the octave - so it is stored as data.

